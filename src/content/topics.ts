function assertTopics(list: Topic[]) {
  if (list.length < 8 || list.length > 12) {
    throw new Error(`Expected 8–12 reviewed topics, found ${list.length}.`);
  }

  const ids = new Set(list.map((topic) => topic.id));
  const banned = ["تسعة وتسعين", "٩٩ اسم", "99 names", "mock theology"];
  const blob = JSON.stringify(list);
  for (const marker of banned) {
    if (blob.includes(marker)) {
      throw new Error(`Blocked an unsupported claim marker: ${marker}`);
    }
  }

  for (const topic of list) {
    if (topic.id !== topic.slug) throw new Error(`Id and slug differ: ${topic.id}`);
    if (!topic.sourceVerified) throw new Error(`${topic.id} is not source-verified.`);
    if (topic.dorarReferences.length > 0) {
      throw new Error(`${topic.id} must not ship static Dorar text.`);
    }
    if (topic.bookReferences.length === 0) throw new Error(`${topic.id} has no book reference.`);
    for (const reference of topic.bookReferences) {
      if (reference.bookTitle !== book.title) throw new Error(`${topic.id} cites an unapproved book.`);
      if (!reference.page || reference.excerpt.trim().length < 40) {
        throw new Error(`${topic.id} has a thin book excerpt.`);
      }
    }
    for (const field of [topic.shortExplanation, topic.detailedExplanation, topic.deepExplanation]) {
      if (field.kind !== "simplified-draft" || !field.text.trim()) {
        throw new Error(`${topic.id} is missing a separated simplification.`);
      }
    }
    for (const related of topic.relatedTopics) {
      if (!ids.has(related)) throw new Error(`${topic.id} points to a missing topic: ${related}`);
    }
  }
}

assertTopics(topics);

export function getTopic(slug: string): Topic | undefined {
  return topics.find((topic) => topic.slug === slug);
}

export function topicsByType(type: "all" | Topic["type"]): Topic[] {
  if (type === "all") return topics;
  return topics.filter((topic) => topic.type === type);
}
